//! `kb tools` — Claude-prompt-friendly manifest of every CLI verb.
//!
//! Walks the clap `Command` tree at runtime so the manifest never
//! drifts from the binary. Output format: one markdown section per
//! subcommand (`## kb <name>`) with synopsis + description + a curated
//! example invocation. Drop the output into a Claude system prompt to
//! teach the model the surface in one paste.

use anyhow::Result;
use clap::CommandFactory;

/// Shown above `kb --help`: the ten verbs a first-time user (or their
/// agent) needs. Everything else is in the full list below it.
pub const START_HERE: &str = "Start here:\n  \
kb daemon       start the daemon (kb add <dir> first registers a folder)\n  \
kb add          register a source folder as a kb\n  \
kb search       find artifacts (all kbs by default when the daemon serves several)\n  \
kb read         open an artifact in the browser\n  \
kb remember     store a memory\n  \
kb recall       recall memories relevant to a query\n  \
kb why          why is this file the way it is (past sessions)\n  \
kb recollect    has something like this been done before\n  \
kb comments     read and answer review comments\n  \
kb slate        this project's shared working state\n\n  \
`kb tools --core` prints a short manifest of these for an agent instruction file.";

/// The verbs `kb tools --core` documents, in display order.
pub const CORE_VERBS: [&str; 10] = [
    "daemon",
    "add",
    "search",
    "read",
    "remember",
    "recall",
    "why",
    "recollect",
    "comments",
    "slate",
];

/// Hard size budget for the core manifest (bytes) — it is meant to be
/// pasted into foreign-harness instruction files.
pub const CORE_MAX_BYTES: usize = 8 * 1024;

pub fn run(core: bool) -> Result<()> {
    if core {
        print!("{}", core_manifest());
    } else {
        print!("{}", render());
    }
    Ok(())
}

/// The whole manifest as text - what `kb tools` prints, byte for byte.
fn render() -> String {
    let cli = crate::Cli::command();
    let mut out = String::from("# kb CLI surface\n\n");
    out.push_str(
        "Generated by `kb tools`. Walks clap's Command tree so the manifest \
         matches the binary. Drop into a Claude system prompt to teach the \
         model how to drive kb without reading docs.\n\n",
    );
    for sub in cli.get_subcommands() {
        emit(&mut out, sub, "kb");
    }
    out
}

/// First sentence of a command's about text, capped, single line.
fn first_sentence(cmd: &clap::Command) -> String {
    let about = cmd.get_about().map(|a| a.to_string()).unwrap_or_default();
    let flat = about.split_whitespace().collect::<Vec<_>>().join(" ");
    let end = flat
        .find(". ")
        .map(|i| i + 1)
        .unwrap_or(flat.len())
        .min(200);
    let mut cut = end;
    while !flat.is_char_boundary(cut) {
        cut -= 1;
    }
    flat[..cut].to_string()
}

/// The `kb tools --core` manifest: the ten core verbs only, one
/// sentence + one synopsis (subcommands named, not expanded) + one
/// example each. Derived from the clap tree, so it cannot drift.
pub fn core_manifest() -> String {
    let cli = crate::Cli::command();
    let mut out = String::from(
        "# kb core verbs\n\nGenerated by `kb tools --core`. Run `kb tools` for every verb, \
         `kb <verb> --help` for flags.\n\n",
    );
    for name in CORE_VERBS {
        let Some(sub) = cli.get_subcommands().find(|c| c.get_name() == name) else {
            continue;
        };
        let qualified = format!("kb {name}");
        out.push_str(&format!("## {qualified}\n\n{}\n\n", first_sentence(sub)));
        let mut syn = synopsis(sub, &qualified);
        if sub.has_subcommands() {
            let names: Vec<&str> = sub.get_subcommands().map(|c| c.get_name()).collect();
            syn = syn.replace(" <SUBCOMMAND>", &format!(" {{{}}}", names.join("|")));
        }
        out.push_str(&format!("```\n{syn}\n```\n\n"));
        if let Some(example) = example_for(name) {
            out.push_str(&format!("Example:\n```\n{example}\n```\n\n"));
        }
    }
    debug_assert!(out.len() <= CORE_MAX_BYTES, "core manifest over budget");
    out
}

fn emit(out: &mut String, cmd: &clap::Command, parent: &str) {
    let name = cmd.get_name();
    let qualified = format!("{parent} {name}");
    out.push_str(&format!("## {qualified}\n\n"));
    if let Some(about) = cmd.get_about() {
        out.push_str(&format!("{about}\n\n"));
    }
    let synopsis = synopsis(cmd, &qualified);
    out.push_str(&format!("```\n{synopsis}\n```\n\n"));
    if let Some(example) = example_for(name) {
        out.push_str(&format!("Example:\n```\n{example}\n```\n\n"));
    }
    for sub in cmd.get_subcommands() {
        emit(out, sub, &qualified);
    }
}

/// Render a one-line synopsis: `kb foo <POS> [--flag VAL]`. Args
/// preserve clap's required/optional display.
fn synopsis(cmd: &clap::Command, qualified: &str) -> String {
    let mut out = qualified.to_string();
    for arg in cmd.get_arguments() {
        if arg.is_hide_set() {
            continue;
        }
        let id = arg.get_id().as_str();
        if id == "help" || id == "version" {
            continue;
        }
        let fragment = if arg.is_positional() {
            if arg.is_required_set() {
                format!(" <{}>", id.to_uppercase())
            } else {
                format!(" [{}]", id.to_uppercase())
            }
        } else {
            // Long-flag form. Skip short for clarity in the manifest.
            let long = arg
                .get_long()
                .map(|l| format!("--{l}"))
                .unwrap_or_else(|| format!("--{id}"));
            let takes_value = arg.get_action().takes_values();
            if takes_value {
                format!(" [{long} VALUE]")
            } else {
                format!(" [{long}]")
            }
        };
        out.push_str(&fragment);
    }
    if cmd.has_subcommands() {
        out.push_str(" <SUBCOMMAND>");
    }
    out
}

