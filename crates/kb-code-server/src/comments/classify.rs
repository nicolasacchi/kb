//! `comments/1` — the kind taxonomy (D8).
//!
//! Eight kinds, classified in a FIXED precedence so the answer never
//! depends on evaluation order: `generated` and `licence` are decided for
//! a whole RUN of adjacent comment lines, then `commented_code` for a run
//! nothing else claimed, then `directive`/`annotation`/`section` per LINE,
//! then `doc` (a run that sits immediately above a definition) and finally
//! `prose`.
//!
//! ## Why `generated` outranks `doc`
//!
//! A schema-dump banner (`# == Schema Information`, written by a
//! generator and refreshed on migrate) sits immediately above a class
//! with no blank line between them. The pre-`comments/1` doc capture
//! (`extract::capture_doc`, which accepts ANY Ruby comment as doc)
//! therefore reported a column dump as the class's documentation. That is
//! not a tuning problem, it is an ordering one: a block that announces
//! itself as machine-written is never documentation, whatever it is
//! adjacent to.
//!
//! ## Why `commented_code` is a parse, not a regex
//!
//! "Does this text parse as code" has an exact answer for any language
//! with a grammar, and this crate already links eleven. The run's text is
//! re-parsed with the FILE's own grammar and accepted only with zero
//! ERROR/MISSING nodes, behind a cheap punctuation pre-gate (so ordinary
//! prose never pays for a parse) and a shape guard (two lines, or a
//! statement-shaped top-level node) so a single bare word cannot qualify.
//! `bash` is deliberately EXCLUDED: its grammar accepts an arbitrary
//! sequence of words as a command, so the parse carries no signal there
//! and an English sentence would classify as code.

use crate::comments::keywords::KeywordSet;
use serde::{Deserialize, Serialize};

/// The kind vocabulary. Closed — a value outside it is unrepresentable
/// rather than a string a route could invent.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CommentKind {
    Doc,
    Annotation,
    Directive,
    Section,
    Licence,
    Generated,
    CommentedCode,
    Prose,
}

impl CommentKind {
    pub const ALL: &'static [CommentKind] = &[
        CommentKind::Doc,
        CommentKind::Annotation,
        CommentKind::Directive,
        CommentKind::Section,
        CommentKind::Licence,
        CommentKind::Generated,
        CommentKind::CommentedCode,
        CommentKind::Prose,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            CommentKind::Doc => "doc",
            CommentKind::Annotation => "annotation",
            CommentKind::Directive => "directive",
            CommentKind::Section => "section",
            CommentKind::Licence => "licence",
            CommentKind::Generated => "generated",
            CommentKind::CommentedCode => "commented_code",
            CommentKind::Prose => "prose",
        }
    }

    pub fn parse(s: &str) -> Option<CommentKind> {
        CommentKind::ALL.iter().copied().find(|k| k.as_str() == s)
    }
}

