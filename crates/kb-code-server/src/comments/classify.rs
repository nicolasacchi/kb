/// One recognised directive family.
#[derive(Debug, Clone, Copy)]
pub struct DirectiveSpec {
    /// Lowercased prefix matched at the START of the stripped comment
    /// text (the shape every one of these actually takes in the wild).
    pub prefix: &'static str,
    /// The `directive_tool` recorded on the row.
    pub tool: &'static str,
    /// A SUPPRESSION directive silences a checker; only these can be
    /// `unreasoned`. A magic comment / build tag carries a VALUE, not a
    /// justification, and never gets a state.
    pub suppression: bool,
    /// Whether the directive is followed by its own argument list (cop
    /// names, rule ids, error codes). See [`has_reason`].
    pub takes_args: bool,
}

