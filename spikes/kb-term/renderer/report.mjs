// Builds out/report.md from out/results.jsonl (+ out/pw.json). Zero deps.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, 'out');
const rows = fs.existsSync(path.join(out, 'results.jsonl')) ? fs.readFileSync(path.join(out, 'results.jsonl'), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [];
const by = (s) => rows.filter((r) => r.section === s).sort((a, b) => a.key.localeCompare(b.key));
const L = [];
const p = (s = '') => L.push(s);
const f = (n, d = 3) => (typeof n === 'number' ? n.toFixed(d) : String(n));

p('# kb-term T2: kitty placeholder renderer + IIP fallback (Chromium)');
p();
p('Generated by `renderer/report.mjs` from `out/results.jsonl` and `out/pw.json`. Synthetic inputs only.');
p();

// test status
try {
  const pw = JSON.parse(fs.readFileSync(path.join(out, 'pw.json'), 'utf8'));
  const specs = [];
  const walk = (suite, trail) => {
    for (const s of suite.specs || []) for (const t of s.tests) specs.push({ title: s.title, status: t.status, ms: (t.results[0] || {}).duration, err: ((t.results[0] || {}).error || {}).message });
    for (const c of suite.suites || []) walk(c, trail);
  };
  for (const s of pw.suites) walk(s, []);
  const cnt = specs.reduce((a, s) => ((a[s.status] = (a[s.status] || 0) + 1), a), {});
  p('## Test status');
  p();
  p(`Totals: ${JSON.stringify(cnt)}`);
  p();
  p('| test | status | ms |'); p('|---|---|---|');
  for (const s of specs) p(`| ${s.title} | ${s.status} | ${s.ms ?? ''} |`);
  const bad = specs.filter((s) => s.status !== 'expected' && s.status !== 'skipped');
  if (bad.length) { p(); p('### Failures'); for (const b of bad) { p(); p(`**${b.title}**`); p('```'); p(String(b.err || '').replace(/\u001b\[[0-9;]*m/g, '').slice(0, 1500)); p('```'); } }
  p();
} catch (e) { p(`(no pw.json: ${e.message})`); p(); }

p('## Environment (renderer actually used)');
p();
p('| config | webgl | canvases in .xterm-screen | .xterm-rows | cell css px | cell device px |');
p('|---|---|---|---|---|---|');
for (const r of by('env')) { const v = r.value; p(`| ${r.key} | ${v.webgl}${v.webglError ? ' (' + v.webglError + ')' : ''}${v.contextLost ? ' CONTEXT LOST' : ''} | ${v.canvases} | ${v.rowsDisplay} | ${f(v.cell.cssW)} x ${f(v.cell.cssH)} | ${v.cell.devW} x ${v.cell.devH} |`); }
p();

p('### WebGL text diagnostic at DPR 2 (headless software GL, per Chromium flag set)'); p();
for (const r of by('k-diag')) p(`- ${r.key}: ${JSON.stringify(r.value)}`);
p();
p('## (a) pictures sit exactly in their placeholder boxes');
p();
p('Probes: one device pixel inside each visible corner, a 5x5 grid inside, and one device pixel outside left/right/above/below (must be terminal background). Expected colours come from the scenario truth (known quadrant pattern), not from the renderer.');
p();
p('| config | ok/total | corners | grid | outside | image elements | render ms (last) |'); p('|---|---|---|---|---|---|---|');
for (const r of by('a-placement')) { const v = r.value; const k = v.byKind || {}; const g = (x) => (k[x] ? `${k[x].ok}/${k[x].n}` : '-'); p(`| ${r.key} | ${v.ok}/${v.total} | ${g('corner')} | ${g('grid')} | ${g('outside')} | ${v.overlay.imgs} | ${f(v.perf.lastMs, 2)} |`); }
p();
p('First paint: `imgCreated` = picture elements created; `imgCompleteAtCreate` = how many were already decoded when created (preloaded when the ImageDef arrived).'); p();
for (const r of by('a-placement')) p(`- ${r.key}: ${JSON.stringify(r.value.rstats)}`);
p();
p('### Glyph halo: does the U+10EEEE glyph leak around the picture?'); p();
p('Ring of device pixels 3px outside picture A. raw = renderer without the decoration recolour, hidden = with it.'); p();
p('| config | ring pixels | dirty pixels | per side (L/R/T/B) | max r+g+b | decorations created |'); p('|---|---|---|---|---|---|');
for (const r of by('j-halo')) { const v = r.value; p(`| ${r.key} | ${v.ringPixels} | ${v.dirtyPixels} | ${v.dirty.left}/${v.dirty.right}/${v.dirty.top}/${v.dirty.bottom} | ${v.maxChannelSum} | ${v.stats ? v.stats.decosCreated : ''} |`); }
p();
p('### Colour-id encodings (24-bit, palette 38;5;n, implicit-continuation cells)'); p();
for (const r of by('a2-encodings')) p(`- ${r.key}: probes ${r.value.ok}/${r.value.total}, decoded ids ${JSON.stringify(r.value.decodedIds)}, placeholder cells ${r.value.cells}`);
p();
p('### Width table: does U+10EEEE + diacritic stay in one cell?'); p();
p('| width table | diacritics tested | broken (not 0-width / split across cells) | examples |'); p('|---|---|---|---|');
for (const r of by('h-width')) p(`| ${r.key} | ${r.value.total} | ${r.value.badCount} | ${JSON.stringify(r.value.bad.slice(0, 6))} |`);
p();
p('### Pipeline per width table (basic scenario at DPR 1, DOM renderer)'); p();
p('| width table | placeholder cells found (expected 520) | probes ok/total |'); p('|---|---|---|');
for (const r of by('h2-pipeline')) p(`| ${r.key} | ${r.value.cellsFound} | ${r.value.probesOk}/${r.value.probesTotal} |`);
p();

p('## (b) sharpness (Laplacian energy, higher = sharper)');
p();
p('Source: 2x device-resolution fine checker. Reference = the same source downscaled once by a canvas to the exact device box. ratio = rendered/reference. control = same picture rendered at DPR 1 and bilinear-upscaled to the DPR (what a CSS-resolution raster looks like).');
p();
p('| config | energy rendered | energy reference | ratio | control (CSS-res upscaled) |'); p('|---|---|---|---|---|');
for (const r of by('b-sharpness')) { const v = r.value; p(`| ${r.key} | ${f(v.energyRender, 1)} | ${f(v.energyReference, 1)} | ${f(v.ratio)} | ${f(v.controlCssResolutionUpscaled)} |`); }
p();

p('## (c) late joiner (headless serialize() into a fresh page terminal)');
p();
for (const r of by('c-latejoin')) {
  const v = r.value;
  p(`### ${r.key}`); p();
  p(`- buffer lines live/late: ${v.liveLen}/${v.lateLen}; twin buffer ${JSON.stringify(v.twin)}; serialized ${v.serializedBytes} bytes in ${v.serializeMs} ms`);
  p(`- placeholder cells live/late: ${v.placeholderCellsLive}/${v.placeholderCellsLate}; identical (abs line, col, id, row, col): ${v.sameCells}`);
  p('| picture line | offset | viewportY live/late | live probes | late probes | screenshots byte-identical |'); p('|---|---|---|---|---|---|');
  for (const x of v.results) p(`| ${x.line0} | ${x.off} | ${x.vyLive}/${x.vyLate} | ${x.liveOk} | ${x.lateOk} | ${x.identicalBytes} |`);
  p();
}

p('## (d) fast scroll through ~2,040 buffer rows, 4 pictures, 10 sampled positions');
p();
p('| config | frames swept | frames where overlay lagged the viewport | samples ok | avg overlay render ms | fast-jump ms |'); p('|---|---|---|---|---|---|');
for (const r of by('d-scroll')) { const v = r.value; p(`| ${r.key} | ${v.sweep.frames} | ${v.sweep.stale} | ${v.samples.filter((s) => s.bad.length === 0 && s.overlayChildren === s.visibleTruth).length}/${v.samples.length} | ${f(v.perf.avgRenderMs, 2)} | ${f(v.fastJumpMs, 0)} |`); }
p();

p('## (e) buffer trimmed through the middle of a picture');
p();
p('| config | lines written | buffer lines | rows trimmed | probes viewportY 0 | probes viewportY 5 |'); p('|---|---|---|---|---|---|');
for (const r of by('e-trimmed')) { const v = r.value; p(`| ${r.key} | ${v.linesWritten} | ${v.bufLen} | ${v.trimmed} (expected ${v.expectedTrim}) | ${v.probesAtTop} | ${v.probesAtVy5} |`); }
p();

p('## (f) unknown id');
p();
p('| config | missing boxes before | text | neutral corner pixels | after ImageDef arrives: missing/imgs, probes |'); p('|---|---|---|---|---|');
for (const r of by('f-unknown')) { const v = r.value; p(`| ${r.key} | ${v.overlayBefore.missing} | ${JSON.stringify(v.overlayBefore.texts)} | ${v.neutral} | ${v.overlayAfter.missing}/${v.overlayAfter.imgs}, ${v.afterProbes} |`); }
p();

p('## (g) GfxReset then re-transmit with the same id');
p();
for (const r of by('g-gfxreset')) { p(`### ${r.key}`); p(); p('```json'); p(JSON.stringify(r.value, null, 1)); p('```'); p(); }

p('## IIP fallback (OSC 1337 File= through @xterm/addon-image 0.9.0)');
p();
p('### Blur and drawn size'); p();
p('| mode / config | drawn bbox css px | box css px (30x8 cells) | stored canvas px | energy ratio vs reference |'); p('|---|---|---|---|---|');
for (const r of by('i-iip-blur')) { const v = r.value; p(`| ${r.key} | ${f(v.drawnCssPx.w, 1)} x ${f(v.drawnCssPx.h, 1)} | ${f(v.boxDevicePx.w / v.dpr, 1)} x ${f(v.boxDevicePx.h / v.dpr, 1)} | ${v.storedCanvas ? v.storedCanvas.w + ' x ' + v.storedCanvas.h : 'n/a'} | ${f(v.ratioVsReference)} |`); }
p();
p('### Storage limit (FIFO eviction)'); p();
p('| case | written | survivors | first/last surviving index | theoretical capacity | usage MB / limit | internal map size | fill ms |'); p('|---|---|---|---|---|---|---|---|');
for (const r of by('i-iip-eviction')) { const v = r.value; p(`| ${r.key} | ${v.imagesWritten} | ${v.survivors} | ${v.firstSurvivorIndex}/${v.lastSurvivorIndex} | ${v.theoreticalCapacity} | ${f(v.usageMB, 1)} / ${v.storageLimitMB} | ${v.internalMapSize} | ${v.fillMs} |`); }
p();
p('## Screenshots'); p();
p('See `screenshots/` (named by test and config).');
fs.writeFileSync(path.join(out, 'report.md'), L.join('\n') + '\n');
console.log('wrote report.md', L.length, 'lines');
